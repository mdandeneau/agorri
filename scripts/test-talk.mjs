// Offline test of functions/api/talk.js against a real SQLite database standing in for Cloudflare D1. Run: node scripts/test-talk.mjs
import { DatabaseSync } from 'node:sqlite';
import fs from 'node:fs';
import { onRequest, checkText } from '../functions/api/talk.js';
const db = new DatabaseSync(':memory:');
db.exec(fs.readFileSync(new URL('../migrations/0001_talk.sql', import.meta.url), 'utf8'));
const D1 = { prepare(sql) { let a = []; const st = { bind(...x) { a = x; return st; }, async all() { return { results: db.prepare(sql).all(...a) }; }, async first() { return db.prepare(sql).get(...a) ?? null; }, async run() { const r = db.prepare(sql).run(...a); return { success: true, meta: { changes: r.changes } }; } }; return st; } };
let ok = 0, bad = 0; const t = (name, cond) => { cond ? ok++ : bad++; console.log((cond ? 'PASS ' : 'FAIL ') + name); };
const call = async (method, body, cid = 'alice', env = { DB: D1, TALK_SALT: 's' }, extra = {}) => {
  const init = { method, headers: { 'x-agorri-client': cid, 'content-type': 'application/json', origin: 'https://agorri.com', ...extra } };
  const url = method === 'GET' ? 'https://agorri.com/api/talk?town=' + (body || 'portsmouth') : 'https://agorri.com/api/talk';
  if (method !== 'GET') init.body = JSON.stringify(body);
  const r = await onRequest({ request: new Request(url, init), env });
  return { status: r.status, j: await r.json() };
};
t('no database: 503 so the page falls back', (await call('GET', 'portsmouth', 'alice', {})).status === 503);
t('privacy filter: phone', checkText('Call 603-555-1212', '') !== '');
t('privacy filter: email', checkText('mail me a@b.com', '') !== '');
let r = await call('POST', { town: 'portsmouth', action: 'post', item: { id: 'i1', kind: 'idea', title: 'Add a crosswalk at Islington and Cass', body: 'Kids cross here.' }, name: 'marc' });
t('post an idea', r.status === 200 && r.j.key.endsWith('~i1'));
const ideaKey = r.j.key;
t('raw browser id is never stored', !ideaKey.startsWith('alice'));
r = await call('POST', { town: 'portsmouth', action: 'post', item: { id: 'a1', kind: 'argument', stance: 'against', body: 'Visitors will circle longer.', ref: { t: 'issue', id: 'parking' } } }, 'bob');
t('post a debate argument on an issue', r.status === 200);
r = await call('POST', { town: 'portsmouth', action: 'post', item: { id: 'r1', kind: 'comment', body: 'Agree, add a beacon.', parent: ideaKey } }, 'bob');
t('reply to a post', r.status === 200);
r = await call('POST', { town: 'portsmouth', action: 'post', item: { id: 'x', kind: 'idea', title: 'Call me 603-555-1212' } });
t('phone number rejected', r.status === 400 && /phone/.test(r.j.error));
r = await call('POST', { town: 'portsmouth', action: 'post', item: { id: 'x', kind: 'idea', title: 'Hello there' } }, 'alice', undefined, { origin: 'https://evil.example' });
t('cross-site post refused', r.status === 403);
await call('POST', { town: 'portsmouth', action: 'support', key: ideaKey }, 'bob');
await call('POST', { town: 'portsmouth', action: 'support', key: ideaKey }, 'carol');
r = await call('GET', 'portsmouth', 'bob');
let idea = r.j.items.find(x => x.key === ideaKey);
t('list: newest first, counts and replies', r.j.items.length === 3 && idea.sup === 2 && idea.supported && idea.replies === 1 && !idea.mine);
t('list: debate keeps stance and issue', r.j.items.some(x => x.kind === 'argument' && x.stance === 'against' && x.ref.t === 'issue' && x.ref.id === 'parking'));
t('list: reply stored as comment with parent', r.j.items.some(x => x.parent === ideaKey && x.kind === 'comment'));
await call('POST', { town: 'portsmouth', action: 'support', key: ideaKey }, 'bob');
idea = (await call('GET', 'portsmouth', 'bob')).j.items.find(x => x.key === ideaKey);
t('support toggles off', idea.sup === 1 && !idea.supported);
t('cannot report own post', (await call('POST', { town: 'portsmouth', action: 'report', key: ideaKey }, 'alice')).status === 400);
for (const c of ['bob', 'carol', 'dave']) await call('POST', { town: 'portsmouth', action: 'report', key: ideaKey }, c);
idea = (await call('GET', 'portsmouth', 'erin')).j.items.find(x => x.key === ideaKey);
t('three reports hide the text from others', idea.hidden && idea.title === '' && idea.body === '');
idea = (await call('GET', 'portsmouth', 'alice')).j.items.find(x => x.key === ideaKey);
t('author still sees their hidden post', idea.hidden && idea.mine && idea.title.startsWith('Add a crosswalk'));
t('only the author can delete', (await call('POST', { town: 'portsmouth', action: 'delete', key: ideaKey }, 'bob')).status === 403);
t('author deletes', (await call('POST', { town: 'portsmouth', action: 'delete', key: ideaKey }, 'alice')).status === 200);
t('other towns are separate', (await call('GET', 'nashua')).j.items.length === 0);
for (let i = 0; i < 5; i++) await call('POST', { town: 'nashua', action: 'post', item: { id: 'q' + i, kind: 'question', title: 'Question number ' + i } }, 'frank');
t('rate limit after 5 posts in 10 minutes', (await call('POST', { town: 'nashua', action: 'post', item: { id: 'q9', kind: 'question', title: 'One more question' } }, 'frank')).status === 429);
console.log(`\n${ok} passed, ${bad} failed`); process.exit(bad ? 1 : 0);
